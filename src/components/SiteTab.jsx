// Get elements by category
const getElementsByCategory = () => {
  const grouped = {}
  Object.values(ELEMENT_TYPES).forEach(type => {
    if (type.autoGenerated) return // Skip auto-generated types
    if (!grouped[type.category]) grouped[type.category] = []
    grouped[type.category].push(type)
  })
  return grouped
}


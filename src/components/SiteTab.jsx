// MAIN SITE TAB COMPONENT (REBUILT)
// ============================================

export default function SiteTab({ project, onUpdate, equipment }) {
  const sites = project.sites || [{ id: 'site-1', name: 'Site 1' }]
  const [activeSiteId, setActiveSiteId] = useState(sites[0]?.id || 'site-1')
  const [selectedElementType, setSelectedElementType] = useState('flight_area')
  const [activeTool, setActiveTool] = useState(null) // 'select', 'delete', or null (drawing)
  const [isMapFullscreen, setIsMapFullscreen] = useState(false)

  const toggleMapFullscreen = useCallback(() => {
    setIsMapFullscreen(prev => !prev)
  }, [])

  // Placeholder for element highlighting - can be expanded later
  const handleHighlightElement = useCallback((elementId) => {
    // TODO: Implement map highlight/zoom to element
    console.log('Highlight element:', elementId)
  }, [])

  const activeSite = sites.find(s => s.id === activeSiteId) || sites[0]
  const activeSiteIndex = sites.findIndex(s => s.id === activeSiteId)

  const updateSites = (newSites) => {
    onUpdate({ sites: newSites })
  }

  const addSite = () => {
    const newSite = {
      id: `site-${Date.now()}`,
      name: `Site ${sites.length + 1}`
    }
    updateSites([...sites, newSite])
    setActiveSiteId(newSite.id)
  }

  const removeSite = (siteId) => {
    if (sites.length <= 1) return
    const newSites = sites.filter(s => s.id !== siteId)
    updateSites(newSites)
    if (activeSiteId === siteId) {
      setActiveSiteId(newSites[0].id)
    }
  }

  const renameSite = (siteId, newName) => {
    updateSites(sites.map(s => s.id === siteId ? { ...s, name: newName } : s))
  }

  const updateActiveSite = (updates) => {
    updateSites(sites.map(s => s.id === activeSiteId ? { ...s, ...updates } : s))
  }

  const updateElement = (elementId, updates) => {
    const elements = activeSite?.elements || []
    const newElements = elements.map(el =>
      el.id === elementId ? { ...el, ...updates } : el
    )
    updateActiveSite({ elements: newElements })
  }

  const deleteElement = (elementId) => {
    const elements = activeSite?.elements || []
    updateActiveSite({ elements: elements.filter(el => el.id !== elementId) })
  }

  // Update element in any site (for the element tables that show all sites)
  const updateSiteElement = (siteId, elementId, updates) => {
    updateSites(sites.map(s => {
      if (s.id !== siteId) return s
      const elements = s.elements || []
      const newElements = elements.map(el =>
        el.id === elementId ? { ...el, ...updates } : el
      )
      return { ...s, elements: newElements }
    }))
  }

  // Delete element from any site
  const deleteSiteElement = (siteId, elementId) => {
    updateSites(sites.map(s => {
      if (s.id !== siteId) return s
      const elements = s.elements || []
      return { ...s, elements: elements.filter(el => el.id !== elementId) }
    }))
  }

  const handleSelectType = (typeId) => {
    setSelectedElementType(typeId)
    setActiveTool(null) // Switch back to drawing mode
  }

  const handleSelectTool = (tool) => {
    setActiveTool(tool)
  }

  // Calculate highest SAIL across all sites
  const getSiteSAIL = (site) => {
    const sora = site?.sora || {}
    const population = sora.population || 'populated'
    const uaCategory = sora.ua_category || '3m_25ms'
    const iGRC = GRC_MATRIX[population]?.[uaCategory] || 5

    const mitigations = sora.mitigations || {}
    let mitigationReduction = 0
    Object.entries(GROUND_MITIGATIONS).forEach(([key, config]) => {
      const level = mitigations[key]?.level || 'none'
      mitigationReduction += config.reductions[level] || 0
    })
    const fGRC = Math.max(1, iGRC + mitigationReduction)

    const initialARC = sora.initial_arc || 'ARC-b'
    const tmprType = sora.tmpr?.type || 'VLOS'
    const tmprOption = TMPR_OPTIONS.find(t => t.value === tmprType)
    const arcIndex = ARC_LEVELS.findIndex(a => a.value === initialARC)
    const residualArcIndex = Math.max(0, arcIndex - (tmprOption?.reduction || 0))
    const residualARC = ARC_LEVELS[residualArcIndex]?.value || 'ARC-a'

    return fGRC <= 7 ? SAIL_MATRIX[fGRC]?.[residualARC] || 'VI' : 'N/A'
  }

  const sailOrder = ['I', 'II', 'III', 'IV', 'V', 'VI']
  const highestSAIL = sites.reduce((highest, site) => {
    const sail = getSiteSAIL(site)
    if (sail === 'N/A') return highest
    if (!highest) return sail
    return sailOrder.indexOf(sail) > sailOrder.indexOf(highest) ? sail : highest
  }, null)

  // Count elements by category for badges
  const elementCounts = useMemo(() => {
    const elements = activeSite?.elements || []
    return {
      total: elements.length,
      areas: elements.filter(e => ELEMENT_TYPES[e.elementType]?.category === 'areas').length,
      routes: elements.filter(e => ELEMENT_TYPES[e.elementType]?.category === 'routes').length,
      points: elements.filter(e => ELEMENT_TYPES[e.elementType]?.category === 'points').length,
      hazards: elements.filter(e => ELEMENT_TYPES[e.elementType]?.category === 'hazards').length
    }
  }, [activeSite?.elements])

  return (
    <div className="space-y-6">
      {/* Site Selector */}
      <div className="bg-white rounded-xl border border-gray-200 p-4">
        <div className="flex items-center justify-between flex-wrap gap-4">
          <SiteSelector
            sites={sites}
            activeSiteId={activeSiteId}
            onSelectSite={setActiveSiteId}
            onAddSite={addSite}
            onRemoveSite={removeSite}
            onRenameSite={renameSite}
          />

          {highestSAIL && (
            <div className="flex items-center gap-2">
              <span className="text-sm text-gray-500">Governing SAIL:</span>
              <span className={`px-3 py-1 rounded-full text-white font-bold ${SAIL_COLORS[highestSAIL] || 'bg-gray-500'}`}>
                {highestSAIL}
              </span>
            </div>
          )}
        </div>
      </div>

      {/* Fullscreen Map Overlay */}
      {isMapFullscreen && (
        <div className="fixed inset-0 z-50 bg-white flex">
          {/* Left sidebar in fullscreen */}
          <div className="w-80 border-r border-gray-200 p-4 overflow-y-auto flex-shrink-0">
            <div className="flex items-center justify-between mb-4">
              <h3 className="font-semibold text-gray-800 flex items-center gap-2">
                <Plane className="w-5 h-5 text-brand-600" />
                Flight Planning
              </h3>
              <button
                onClick={toggleMapFullscreen}
                className="p-2 text-gray-500 hover:text-gray-700 hover:bg-gray-100 rounded-lg"
                title="Exit fullscreen"
              >
                <Minimize2 className="w-5 h-5" />
              </button>
            </div>
            <div className="space-y-4">
              <ElementToolbar
                selectedType={selectedElementType}
                onSelectType={handleSelectType}
                activeTool={activeTool}
                onSelectTool={handleSelectTool}
              />
              <FlightParameters
                site={activeSite}
                onUpdateSite={updateActiveSite}
              />
            </div>
          </div>

          {/* Map in fullscreen */}
          <div className="flex-1 p-4 flex flex-col min-w-0">
            <SiteMap
              site={activeSite}
              allSites={sites}
              onUpdateSite={updateActiveSite}
              selectedType={selectedElementType}
              activeTool={activeTool}
              flightParams={activeSite?.flightParams}
              isFullscreen={true}
              onToggleFullscreen={toggleMapFullscreen}
              siteIndex={activeSiteIndex}
            />
          </div>
        </div>
      )}

      {/* Map Section with Toolbar (normal view) */}
      <Section
        title="Map & Flight Planning"
        icon={Plane}
        badge={`${elementCounts.total} elements`}
      >
        <div className="grid grid-cols-1 lg:grid-cols-4 gap-6">
          {/* Left sidebar: Toolbar */}
          <div className="lg:col-span-1 space-y-4">
            <ElementToolbar
              selectedType={selectedElementType}
              onSelectType={handleSelectType}
              activeTool={activeTool}
              onSelectTool={handleSelectTool}
            />
            <FlightParameters
              site={activeSite}
              onUpdateSite={updateActiveSite}
            />
          </div>

          {/* Map and element table */}
          <div className="lg:col-span-3 space-y-6">
            <SiteMap
              site={activeSite}
              allSites={sites}
              onUpdateSite={updateActiveSite}
              selectedType={selectedElementType}
              activeTool={activeTool}
              flightParams={activeSite?.flightParams}
              isFullscreen={false}
              onToggleFullscreen={toggleMapFullscreen}
              siteIndex={activeSiteIndex}
            />

            <div className="border-t pt-6">
              <h4 className="text-sm font-semibold text-gray-700 mb-4 flex items-center gap-2">
                <Layers className="w-4 h-4" />
                Map Elements
              </h4>
              <ElementTables
                sites={sites}
                onUpdateSiteElement={updateSiteElement}
                onDeleteSiteElement={deleteSiteElement}
                onHighlight={handleHighlightElement}
              />
            </div>
          </div>
        </div>
      </Section>

      {/* SORA Calculator */}
      <Section title="SORA Assessment" icon={Shield} badge={`SAIL ${getSiteSAIL(activeSite)}`}>
        <SORACalculator
          site={activeSite}
          onUpdateSite={updateActiveSite}
          equipment={equipment}
        />
      </Section>

      {/* Hazard Identification */}
      <Section title="Hazard Identification" icon={AlertTriangle} badge={`${(activeSite?.hazards || []).length} hazards`}>
        <HazardTable
          site={activeSite}
          onUpdateSite={updateActiveSite}
        />
      </Section>

      {/* Emergency Planning */}
      <Section title="Emergency Planning" icon={ShieldAlert} defaultOpen={false}>
        <EmergencyPlanning
          site={activeSite}
          onUpdateSite={updateActiveSite}
        />
      </Section>
    </div>
  )
}

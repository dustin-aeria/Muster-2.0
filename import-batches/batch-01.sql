| **Pre-flight/post-flight checklists** | 3 years |
| **Maintenance records** | See MCM |
| **Training records** | See TCP |

### 4.5 Incident Data Preservation

**If any incident or occurrence:**
1. Do not delete or overwrite data
2. Immediately preserve all flight data
3. Download telemetry before data is overwritten
4. Store separately with incident reference
5. Make copies for investigation

### 4.6 Data Security

Flight data shall be:
- Stored securely
- Backed up regularly
- Protected from unauthorized access
- Available for regulatory inspection if required

### 4.7 Flight Time Tracking

**Track for each pilot:**
- Total flight time (rolling 12 months)
- Flight time by aircraft type
- BVLOS flight time (separately)
- Training flight time

**Track for each aircraft:**
- Total flight hours
- Flights since maintenance
- Battery cycles

### 4.8 Reporting

Monthly reporting includes:
- Total flights
- Total flight hours
- Incidents/occurrences
- Pilot currency status
- Aircraft utilization

Operations Manager reviews monthly reports.

### 4.9 Regulatory Access

Flight records shall be made available to Transport Canada upon request:
- Within 48 hours for serious investigations
- Within 30 days for routine requests
- In format readable by the authority


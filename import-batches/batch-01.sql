## 4. Policy

### 4.1 Flight Logging Requirements

**Every flight shall be logged.**

The flight log shall include:
- Date
- PIC name
- Aircraft registration/identifier
- Location (coordinates or description)
- Flight start and end times
- Total flight time
- Type of operation (VLOS/BVLOS, category)
- Purpose of flight

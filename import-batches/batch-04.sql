| First Aid | Location of first aid, who to contact |
| Key Contacts | Supervisors, safety contacts |

**See:** TCP-001-PR New Personnel Orientation Procedure

### 4.3 Task-Specific Training

Workers shall receive specific training for:
- Each task they are assigned
- Equipment they will operate
- Hazards specific to their work
- Required PPE and its proper use
- Applicable safe work procedures

Training shall include practical demonstration of competency, not just information transfer.

### 4.4 Site-Specific Training

Before working at any new site, workers shall be oriented to:
- Site-specific hazards
- Site emergency procedures
- Site rules and requirements
- Client safety requirements (if applicable)
- Location of emergency equipment

### 4.5 Supervisor Training

Supervisors (including PICs) shall receive additional training in:
- Hazard recognition and control
- Conducting effective briefings
- Addressing unsafe conditions and behaviors
- Incident response and reporting
- Worker rights and employer duties

### 4.6 Competency Verification

1. Training shall include verification that workers:
   - Understand the information provided
   - Can perform tasks safely
   - Know what to do in emergencies

2. Competency may be verified through:
   - Practical demonstration
   - Written or verbal assessment
   - Observation during work
   - Sign-off by trainer or supervisor

### 4.7 Training Records

Training records shall include:
- Worker name
- Training topic and content
- Date and duration
- Trainer name and qualifications
- Competency verification method
- Worker signature

Records shall be retained per ADM-001-PR Record Retention Procedure.

### 4.8 Refresher Training

Refresher training shall be provided:
- As specified in FHAs or procedures
- Following incidents or near-misses
- When performance deficiencies are observed
- At intervals defined in TCP-001


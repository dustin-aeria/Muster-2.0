## 4. Policy

### 4.1 Hierarchy of Controls

Hazards shall be controlled using the hierarchy of controls, applied in order of effectiveness:

| Priority | Control Type | Description | Example |
|:---------|:-------------|:------------|:--------|
| **1** | **Elimination** | Remove the hazard completely | Cancel flight in dangerous weather |
| **2** | **Substitution** | Replace with less hazardous alternative | Use different flight path to avoid obstacle |
| **3** | **Engineering** | Physical changes to isolate or reduce hazard | Geofencing, barriers, guarding |
| **4** | **Administrative** | Procedures, training, signage, scheduling | SOPs, checklists, briefings, work rotation |
| **5** | **PPE** | Personal protective equipment | Safety glasses, hi-vis, hearing protection |

**Key Principles:**
- Always start at the top of the hierarchy
- Use lower-level controls only when higher-level controls are not reasonably practicable
- Multiple controls may be needed (defense in depth)
- PPE is the last resort, not the first choice

### 4.2 Control Requirements

1. **Identified hazards shall be controlled before work proceeds.**

2. Controls shall be:
   - Appropriate for the hazard and risk level
   - Reasonably practicable to implement
   - Communicated to all affected workers
   - Verified as effective

3. Where hazards cannot be eliminated, controls shall reduce risk to as low as reasonably practicable (ALARP).

### 4.3 Control Implementation

| Risk Level | Control Requirement |
|:-----------|:-------------------|
| **Critical** | Elimination or substitution required; do not proceed without |
| **High** | Engineering or strong administrative controls; supervisor approval |
| **Medium** | Administrative controls minimum; document in FLHA |
| **Low** | Awareness and monitoring; standard procedures |

### 4.4 Control Verification

Controls shall be verified:
- Before work begins (confirm controls in place)
- During work (monitor effectiveness)
- After changes (confirm controls still appropriate)
- Following incidents (assess control failure)

### 4.5 Control Failure

If a control fails or becomes ineffective:
1. Stop work immediately if risk is unacceptable
2. Notify supervisor/PIC
3. Implement alternative controls
4. Document the failure
5. Report per incident reporting requirements
6. Review and improve controls

### 4.6 Safe Work Procedures

Written safe work procedures shall be developed for:
- Tasks with high or critical risk
- Tasks where specific sequence is important
- Tasks requiring specific training or authorization
- Tasks identified through incident investigation


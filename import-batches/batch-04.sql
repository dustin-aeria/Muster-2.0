## 4. Policy

### 4.1 Right to Refuse

**Every worker has the right to refuse work they believe presents an undue hazard to themselves or others.**

An undue hazard is a hazard that poses a risk greater than normally expected for the job when done safely.

### 4.2 No Reprisal

**Aeria Solutions will not take or threaten any disciplinary or discriminatory action against a worker who exercises their right to refuse unsafe work.**

This protection applies regardless of the outcome of the investigation.

### 4.3 When to Refuse

Workers should refuse work when they have reasonable grounds to believe:
- The work poses an undue hazard to their health or safety
- Equipment, conditions, or practices are unsafe
- Required safety controls are not in place
- They lack training or competency for the task
- Conditions have changed making work unsafe

### 4.4 Refusal Procedure

#### Step 1: Report the Concern
- Immediately inform your supervisor or PIC
- Explain why you believe the work is unsafe
- Do not perform the work until the matter is resolved

#### Step 2: Investigation
- Supervisor/PIC shall investigate immediately
- Investigation shall involve the refusing worker
- Hazard shall be assessed
- Supervisor shall attempt to resolve the concern

#### Step 3: Resolution Attempted
If the supervisor determines the work is safe:
- Explain findings to the worker
- Explain what controls make the work safe
- If worker accepts, work may proceed

#### Step 4: Continued Refusal
If the worker still believes the work is unsafe:
- Worker has the right to continue refusing
- Contact Operations Manager
- Contact WorkSafeBC if not resolved internally
- Worker shall remain at work location (or be assigned other work)
- No other worker shall be assigned the refused work until the matter is resolved (unless informed of the refusal and reasons)

### 4.5 WorkSafeBC Involvement

If the matter cannot be resolved internally:
- Either party may contact WorkSafeBC
- A prevention officer may investigate
- The officer''s decision is binding (subject to appeal)
- Full cooperation with the officer is required

### 4.6 Other Workers

No worker shall be required to perform work that another worker has refused until:
- The matter has been resolved, OR
- The new worker has been informed of:
  - The refusal
  - The reasons for the refusal
  - The right to also refuse

### 4.7 Documentation

All refusals shall be documented including:
- Date, time, location
- Worker''s name
- Nature of the refusal and reasons given
- Investigation findings
- Actions taken
- Resolution

Records shall be retained and kept confidential.

### 4.8 Alternative Work

While a refusal is being investigated:
- The refusing worker may be assigned reasonable alternative work
- The worker shall remain available at the work location
- Pay and benefits continue as normal


| Risk Level | Action Required |
|:-----------|:----------------|
| **Critical** | Do not proceed until risk is reduced |
| **High** | Contact Operations Manager; implement additional controls |
| **Medium** | Implement controls; proceed with caution |
| **Low** | Awareness; standard procedures |

#### Step 5: Identify Controls

For each hazard, determine:
- What controls will reduce the risk
- Who is responsible for implementing
- How effectiveness will be verified

Controls should follow the hierarchy:
1. Can we eliminate the hazard?
2. Can we substitute something safer?
3. Can we physically separate workers from the hazard?
4. What procedures or warnings do we need?
5. What PPE is required?

#### Step 6: Document and Brief

- Record all findings on FRM-FLHA
- Brief all crew members
- Ensure everyone understands hazards and controls
- Have all participants sign the FLHA

#### Step 7: Keep FLHA Active

The FLHA is a living document:
- Update if conditions change
- Re-brief if new hazards appear
- Add notes as work progresses
- Complete weather updates if required


## 4. Policy

### 4.1 General Requirements

1. **No worker shall perform a task until they have received adequate training** for that task.

2. Training shall ensure workers can:
   - Recognize hazards in their work
   - Understand and apply controls
   - Perform tasks safely
   - Respond to emergencies

3. Training shall be provided:
   - Before starting work (orientation)
   - When tasks or conditions change
   - When new hazards are introduced
   - As refresher training at defined intervals

### 4.2 Orientation Training

All new workers shall complete orientation before starting work, including:

| Topic | Content |
|:------|:--------|
| Health & Safety Policy | HSE-001 review and commitment |
| Worker Rights & Responsibilities | HSE-002 review |
| Hazard Assessment | How FLHAs work; worker participation |
| Hazard Reporting | How to report hazards and incidents |
| Emergency Procedures | Site-specific emergency response |
| PPE Requirements | Required equipment and proper use |

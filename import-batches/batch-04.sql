## 5. Policy

### 5.1 General Requirements

1. **No work shall begin until hazards have been identified and controls are in place.**

2. Hazard assessment shall be:
   - Conducted before work begins
   - Documented appropriately
   - Communicated to all affected workers
   - Updated when conditions change

3. All workers shall participate in hazard assessment activities.

### 5.2 Formal Hazard Assessments (FHAs)

**Purpose:** Identify hazards and controls for standard operations and tasks.

**When Required:**
- All regular work activities (documented in FHA series)
- New operations or tasks
- Changes to equipment, procedures, or environment
- Following incidents that reveal new hazards
- Annual review of existing FHAs

**Content:**
- Description of activity/environment
- Identified hazards
- Risk assessment (likelihood × severity)
- Control measures
- Residual risk
- Training requirements
- Related procedures and PPE

**See:** HSE-001-PR for formal hazard assessment procedure

### 5.3 Field Level Hazard Assessments (FLHAs)

**Purpose:** Identify site-specific and day-specific hazards not covered by FHAs.

**When Required:**
- Before starting work at any site
- At the start of each work day
- When conditions change significantly
- When new hazards are identified

**Process:**
1. Walk the site and observe conditions
2. Identify hazards present
3. Assess risk level
4. Determine controls
5. Communicate to all crew members
6. Document on FLHA form (FRM-FLHA)
7. Update if conditions change

**See:** HSE-002-PR for FLHA procedure

### 5.4 Risk Assessment

Risks shall be assessed using likelihood and severity:

| Likelihood | Description |
|:-----------|:------------|
| **High** | Expected to occur; has happened before |
| **Medium** | Could occur; has occurred in industry |
| **Low** | Unlikely but possible |

| Severity | Description |
|:---------|:------------|
| **High** | Fatality, permanent disability, major damage |
| **Medium** | Medical treatment, lost time, significant damage |
| **Low** | First aid, minor injury, minor damage |

**Risk Matrix:**

|  | Low Severity | Medium Severity | High Severity |
|:---|:---:|:---:|:---:|
| **High Likelihood** | Medium | High | Critical |
| **Medium Likelihood** | Low | Medium | High |
| **Low Likelihood** | Low | Low | Medium |

**Risk Acceptability:**
- **Critical:** Do not proceed until risk is reduced
- **High:** Additional controls required; supervisor approval needed
- **Medium:** Controls required; proceed with awareness
- **Low:** Acceptable; monitor

### 5.5 Worker Participation

All workers shall:
- Participate in FLHA process
- Contribute observations and knowledge
- Report hazards not previously identified
- Suggest control measures
- Sign the FLHA acknowledging participation


- Assistance would not be readily available in emergency
- Communication is limited or unreliable

### 5.2 Working Alone Assessment

Before any lone work:
1. Identify hazards specific to working alone
2. Assess risk level
3. Implement controls
4. Establish check-in procedure
5. Document on FLHA

### 5.3 Risk Considerations

| Factor | Higher Risk | Lower Risk |
|:-------|:------------|:-----------|
| **Location** | Remote, difficult access | Urban, easy access |
| **Communication** | No cell coverage | Reliable communication |
| **Hazards** | High-hazard work, wildlife | Low-hazard, controlled environment |
| **Duration** | Extended periods | Short duration |
| **Time** | Night, extreme weather | Daytime, good conditions |
| **Worker** | New, inexperienced | Trained, experienced |

### 5.4 Prohibited Lone Work

Workers shall NOT work alone when:
- High-hazard work requires buddy system (confined space, heights, etc.)
- Risk assessment indicates unacceptable risk
- Communication is not possible
- Specific hazards require immediate assistance capability (wildlife, remote water)
- Worker is unfit for lone work (medical conditions, inexperience)

### 5.5 Check-In Procedures

| Risk Level | Check-In Frequency | Method |
|:-----------|:-------------------|:-------|
| **Low** | Start and end of day | Phone/text |
| **Medium** | Every 2-4 hours | Phone/text/radio |
| **High** | Every 1-2 hours | Phone/text/radio/satellite |
| **Remote/Extreme** | Continuous monitoring | Satellite tracker with check-in |

### 5.6 Check-In Requirements

1. **Lone Worker Shall:**
   - Check in at agreed times
   - Report changes to plans or location
   - Check in immediately upon safe completion
   - Carry charged communication device(s)

2. **Contact Person Shall:**
   - Know worker''s location and planned activities
   - Expect check-in at specified times
   - Initiate response if check-in missed
   - Have emergency contact information ready

### 5.7 Missed Check-In Response

| Missed By | Action |
|:----------|:-------|
| **15 minutes** | Attempt to contact worker |
| **30 minutes** | Attempt alternative contact methods |
| **1 hour** | Notify Operations Manager; consider dispatching someone |
| **As warranted** | Contact emergency services |

Adjust times based on risk level and circumstances.

### 5.8 Communication Requirements

Lone workers shall have:
- Primary communication device (cell phone)
- Backup communication if in areas with poor coverage
- Satellite communicator for remote operations
- Emergency contact numbers

### 5.9 Training

Lone workers shall be trained in:
- Check-in procedures
- Emergency response when alone
- Use of communication equipment
- When to request assistance
- Self-care and risk awareness

### 5.10 Travel

Workers traveling alone shall:
- File travel plans with contact person
- Check in at major waypoints
- Have emergency supplies and communication
- Not drive fatigued (see HSE-010)


### 4.2 FLHA Process

#### Step 1: Stop and Observe
Before starting work:
- Walk the site perimeter
- Look for hazards in all directions (up, down, around)
- Consider weather and environmental conditions
- Check for changes since last assessment

#### Step 2: Gather the Crew
- All crew members participate in the FLHA
- Each person contributes observations
- Everyone signs the completed FLHA

#### Step 3: Identify Hazards

Consider these categories:

| Category | Examples |
|:---------|:---------|
